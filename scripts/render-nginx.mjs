// Writes dist-nginx/security-headers.conf from scripts/headers.mjs, with the CSP hash of the built theme script.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { distScriptHash, inlineScriptHash, securityHeaders } from './headers.mjs';

const hash = distScriptHash('dist');
// Every page must carry the identical inline script, or the single hash would block it somewhere.
const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : path.endsWith('.html') ? [path] : [];
  });
for (const file of walk('dist')) {
  if (inlineScriptHash(readFileSync(file, 'utf8')) !== hash) throw new Error(`${file} has a different inline script`);
}
const lines = securityHeaders(hash).map(([name, value]) => `add_header ${name} "${value}" always;`);
mkdirSync('dist-nginx', { recursive: true });
writeFileSync(
  'dist-nginx/security-headers.conf',
  `# Generated by scripts/render-nginx.mjs. Do not edit.\n${lines.join('\n')}\n`,
);
console.log(`nginx security headers written (script hash sha256-${hash}).`);
